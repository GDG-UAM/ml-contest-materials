_ANSI = {"bold": 1, "dim": 2, "red": 31, "green": 32, "yellow": 33, "magenta": 35, "cyan": 36}
_vt_enabled = False


def _color(stream=None) -> bool:
    """Whether to style output on `stream` (default stderr): only on a terminal, and NO_COLOR unset."""
    global _vt_enabled
    stream = stream or sys.stderr
    if "NO_COLOR" in os.environ or not getattr(stream, "isatty", lambda: False)():
        return False
    if os.name == "nt" and not _vt_enabled:  # the classic Windows console needs ANSI escapes switched on
        _vt_enabled = True
        with contextlib.suppress(Exception):
            import ctypes
            k32 = ctypes.windll.kernel32
            for std_handle in (-11, -12):  # stdout, stderr
                h, mode = k32.GetStdHandle(std_handle), ctypes.c_uint32()
                if k32.GetConsoleMode(h, ctypes.byref(mode)):
                    k32.SetConsoleMode(h, mode.value | 0x4)  # ENABLE_VIRTUAL_TERMINAL_PROCESSING
    return True


def _paint(text, *styles, stream=None) -> str:
    """`text` wrapped in ANSI codes for `styles` (keys of _ANSI) when `stream` gets colors."""
    if not styles or not _color(stream):
        return str(text)
    return f"\033[{';'.join(str(_ANSI[s]) for s in styles)}m{text}\033[0m"


class _LiveStatus:
    """One status line on stderr, redrawn in place every 0.1 s by a background thread, so the clock
    keeps ticking during setup and slow calls. Only on a terminal; a no-op otherwise.

        with _LiveStatus(project, r) as status:
            status.set("scored", 0.4, "24.0/60s  n=812")  # phase, progress in [0, 1] (None: spinner), details
    """

    SPINNER = "⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏"

    def __init__(self, project, run, live=True):
        self.project, self.run = f"[{project}]", f"run {run}"
        self.state = ("starting", None, "")  # replaced as a whole, so the thread never reads a mix
        self.t0 = time.monotonic()
        self.unicode = "utf" in (getattr(sys.stderr, "encoding", None) or "").lower()
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True) if live and _color() else None

    def __enter__(self):
        if self._thread:
            self._thread.start()
        return self

    def __exit__(self, *exc):
        if self._thread:
            self._stop.set()
            self._thread.join()
            self._write("")

    def set(self, phase, progress=None, details=""):
        self.state = (phase, progress, details)

    def _loop(self):
        while not self._stop.wait(0.1):
            self._write(self._render())

    @staticmethod
    def _write(line):
        sys.stderr.write("\r\033[2K" + line)  # back to column 0, clear the line, draw
        sys.stderr.flush()

    def _render(self) -> str:
        phase, progress, details = self.state
        elapsed = int(time.monotonic() - self.t0)
        clock = f"{elapsed // 60:02d}:{elapsed % 60:02d}"
        # ponytail: a line wider than the terminal wraps and \r can't redraw it; the bar shrinks first
        rest = len(f"  {self.project} {self.run}  {phase:<7}    {details}  {clock}")
        bar_width = min(30, shutil.get_terminal_size().columns - 1 - rest)
        if progress is None:
            spinner = self.SPINNER if self.unicode else "|/-\\"
            bar = _paint(spinner[int(time.monotonic() * 10) % len(spinner)], "cyan")
        elif bar_width >= 8:
            full, empty = ("━", "━") if self.unicode else ("#", "-")
            filled = round(bar_width * min(max(progress, 0.0), 1.0))
            bar = _paint(full * filled, "green") + _paint(empty * (bar_width - filled), "dim")
        else:
            bar = ""
        return (f"  {_paint(self.project, 'cyan')} {_paint(self.run, 'bold')}  {_paint(f'{phase:<7}', 'magenta')}"
                f"  {bar}  {details}  {_paint(clock, 'dim')}")


def _short_reason(reason) -> str:
    """'setup_error: Traceback ... ValueError: msg' -> 'setup_error: ValueError: msg'."""
    lines = [ln.strip() for ln in str(reason).splitlines() if ln.strip()]
    return lines[0] if len(lines) == 1 else f"{lines[0].partition(':')[0]}: {lines[-1]}"


def _run_line(res) -> str:
    """Colored one-line summary of a finished run."""
    def kv(key, value, *styles):
        return _paint(f"{key}=", "dim") + _paint(value, *styles)

    parts = [f"{_paint(f'[{res.project}]', 'cyan')} {_paint(f'run {res.run}', 'bold')}",
             kv("score", f"{res.score:.3f}", "bold", "green" if res.status == "ok" else "red"), kv("n", res.n_scored),
             kv("acc", "-" if res.accuracy_all is None else f"{res.accuracy_all:.3f}")]
    if res.latency_s:
        parts.append(kv("latency", f"{res.latency_s['mean'] * 1e3:.1f}ms"))
    for kind in ("soft_timeout", "hard_timeout", "exception", "invalid"):
        if getattr(res, f"n_{kind}"):
            parts.append(kv(kind, getattr(res, f"n_{kind}"), "yellow"))
    if res.end_reason:
        parts.append(kv("end", res.end_reason))
    if res.status == "ok":
        parts.append(_paint("ok", "green"))
    else:
        parts.append(_paint(f"FAILED: {_short_reason(res.failure_reason)}", "bold", "red"))
    return "  " + "  ".join(parts)


