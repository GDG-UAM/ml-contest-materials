class EvalConfigError(ValueError):
    pass


def resolve_eval_config(overrides=None) -> dict:
    cfg = dict(EVAL_CONFIG)
    for k, v in (overrides or {}).items():
        if k not in EVAL_CONFIG:
            sugg = difflib.get_close_matches(k, list(EVAL_CONFIG), 1)
            raise EvalConfigError(f"unknown EVAL_CONFIG key {k!r}" + (f" (did you mean {sugg[0]!r}?)" if sugg else ""))
        cfg[k] = v
    choices = {"on_warmup_overrun": ("fail_run", "restart_skip_warmup"), "on_hard_timeout": ("end_run", "restart_worker"),
               "seed_torch": ("if_imported", "if_installed", "never")}
    for k, opts in choices.items():
        if cfg[k] not in opts:
            raise EvalConfigError(f"{k} must be one of {opts}, got {cfg[k]!r}")
    if cfg["warmup_enabled"] and not (cfg["warmup_max_samples"] or cfg["warmup_max_time_s"]):
        raise EvalConfigError("warmup needs warmup_max_samples or warmup_max_time_s (or warmup_enabled=False)")
    for k in ("time_budget_s", "per_sample_timeout_s", "setup_timeout_s", "producer_timeout_s"):
        if not cfg[k] or cfg[k] <= 0:
            raise EvalConfigError(f"{k} must be > 0")
    if cfg["grace_s"] < 0 or cfg["n_producers"] < 1 or cfg["n_runs"] < 1 or cfg["lookahead"] < 1:
        raise EvalConfigError("need grace_s >= 0, n_producers >= 1, n_runs >= 1, lookahead >= 1")
    if not (cfg["source"] == "generator" or str(cfg["source"]).startswith("file:")):
        raise EvalConfigError(f"source must be 'generator' or 'file:<path>', got {cfg['source']!r}")
    cfg["score_fn"] = _load_callable(cfg["score_fn"])
    if cfg["aggregation"] not in aggregators(cfg):
        raise EvalConfigError(f"unknown aggregation {cfg['aggregation']!r}; available: {sorted(aggregators(cfg))}")
    return cfg


def _load_callable(f):
    if callable(f):
        return f
    mod, _, attr = str(f).rpartition(":")
    if not mod or not attr:
        raise EvalConfigError(f"expected a callable or 'module:function', got {f!r}")
    if mod.endswith(".py"):
        spec = importlib.util.spec_from_file_location(Path(mod).stem, mod)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
    else:
        m = importlib.import_module(mod)
    return getattr(m, attr)


def _callable_id(f):
    try:
        return inspect.getsource(f).strip()
    except (OSError, TypeError):
        return f"{getattr(f, '__module__', '?')}:{getattr(f, '__qualname__', repr(f))}"


def eval_config_hash(cfg) -> str:
    s = json.dumps(cfg, sort_keys=True, separators=(",", ":"), default=_callable_id)
    return hashlib.sha256(s.encode()).hexdigest()


def run_seeds(master_seed, r) -> dict:
    """Seeds of run r: separate spawned streams for warmup, scored and participant RNGs."""
    run_ss = np.random.SeedSequence(master_seed).spawn(r + 1)[r]
    w, s, p = run_ss.spawn(3)

    def big(ss):
        return int.from_bytes(ss.generate_state(4, np.uint32).tobytes(), "little")
    return {"warmup": big(w), "scored": big(s), "participant": int(p.generate_state(1, np.uint32)[0])}


