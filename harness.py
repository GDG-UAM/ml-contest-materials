class _StreamHash:
    def __init__(self, checkpoints):
        self.h, self.n, self.cp, self.points = hashlib.sha256(), 0, set(checkpoints or ()), {}

    def update(self, i, series, meta, label):
        self.h.update(struct.pack("<qq", i, label))
        self.h.update(np.ascontiguousarray(series, dtype="<f4").tobytes())
        self.h.update(json.dumps(meta, sort_keys=True).encode())
        self.n += 1
        if self.n in self.cp:
            self.points[str(self.n)] = self.h.hexdigest()

    def hexdigest(self):
        return self.h.hexdigest()


OUTCOMES = ("correct", "incorrect", "abstain", "soft_timeout", "hard_timeout", "exception", "invalid")
_OUTCOME_CODE = {o: c for c, o in enumerate(OUTCOMES)}
_RECORD_DTYPES = {"index": np.int64, "y_true": np.int16, "y_pred": np.int16, "outcome": np.int8,
                  "latency": np.float64, "charged": np.float64}  # 29 bytes/sample


class _Run:
    """State of one run: per-sample records (growable numpy columns), error log, clock checks."""

    def __init__(self, res, ecfg):
        self.res, self.ecfg, self.n = res, ecfg, 0
        self._cols = {k: np.empty(1024, d) for k, d in _RECORD_DTYPES.items()}

    def record(self, i, y, pred, outcome, latency, charged):
        if self.n == len(self._cols["index"]):
            for k, a in self._cols.items():
                self._cols[k] = np.resize(a, 2 * len(a))
        for k, v in zip(_RECORD_DTYPES, (i, y, pred, _OUTCOME_CODE[outcome], latency, charged)):
            self._cols[k][self.n] = v
        self.n += 1

    def col(self, k):
        return self._cols[k][:self.n]

    def outcomes(self):
        """Outcome names per sample; object dtype shares the interned strings (8 bytes/sample)."""
        return np.array(OUTCOMES, dtype=object)[self.col("outcome")]

    def log_error(self, phase, i, kind, info):
        if len(self.res.errors) < self.ecfg["error_log_limit"]:
            self.res.errors.append({"phase": phase, "sample_index": i, "kind": kind, "info": info})

    def clock_check(self, p_ns, rt_ns):
        gap = (rt_ns - p_ns) / 1e9
        self.res.max_clock_gap_s = max(self.res.max_clock_gap_s, gap)
        if p_ns < 0 or gap < 0 or gap > max(self.ecfg["clock_check_abs_s"], self.ecfg["clock_check_rel"] * rt_ns / 1e9):
            self.res.clock_flags += 1


def _restart(worker, res, phase, reason, i, waited_ns):
    res.restarts.append({"phase": phase, "reason": reason, "sample_index": i, "waited_s": waited_ns / 1e9})
    ok, info, dt = worker.start()
    res.restarts[-1].update(setup_ok=ok, setup_time_s=dt, setup_error=info)
    return ok


def _warmup(worker, pool, ecfg, res, st, status) -> bool:
    max_n = ecfg["warmup_max_samples"] or None
    max_t = ecfg["warmup_max_time_s"] or None
    per = ecfg["warmup_per_sample_timeout_s"] or math.inf
    h = _StreamHash(())
    cum = max_lat = 0.0
    pool.wait_ready()
    wait0 = pool.wait_ns
    n, reason, t0 = 0, None, _PC()
    while True:
        status.set("warmup", max(n / max_n if max_n else 0, cum / max_t if max_t else 0), f"{n} samples")
        if max_n and n >= max_n:
            reason = "max_samples"
            break
        remaining = max_t - cum if max_t else math.inf
        if remaining <= 0 or (ecfg["warmup_predictive_stop"] and max_lat > remaining):
            reason = "max_time"
            break
        item = pool.get()
        if item is None:
            reason = "stream_exhausted"
            break
        i, series, meta, label, gen_ns = item
        res.warmup_generation_time_s += gen_ns / 1e9
        h.update(i, series, meta, label)
        kind, val, p_ns, rt_ns = worker.predict(series, meta, min(per, remaining) + ecfg["grace_s"])
        if kind in ("timeout", "died"):
            reason = "overrun" if kind == "timeout" else "worker_died"
            worker.kill()
            break
        lat = p_ns / 1e9
        cum += lat
        max_lat = max(max_lat, lat)
        n += 1
        st.clock_check(p_ns, rt_ns)
        if kind == "exception":
            res.warmup_exceptions += 1
            st.log_error("warmup", i, kind, val)
    res.warmup_samples, res.warmup_model_time_s = n, cum
    res.warmup_sample_wait_s = (pool.wait_ns - wait0) / 1e9
    res.warmup_wall_time_s = (_PC() - t0) / 1e9 - res.warmup_sample_wait_s
    res.warmup_end_reason, res.warmup_stream_hash = reason, h.hexdigest()
    if reason in ("overrun", "worker_died"):
        if ecfg["on_warmup_overrun"] == "fail_run":
            res.status, res.failure_reason = "failed", f"warmup_{reason}"
            return False
        status.set("restart", None, f"warmup {reason}")
        if not _restart(worker, res, "warmup", reason, i, rt_ns):
            res.status, res.failure_reason = "failed", "restart_setup_failed"
            return False
    return True


def _scored(worker, pool, ecfg, res, st, h, status):
    K = res.n_classes
    budget, per, grace = ecfg["time_budget_s"], ecfg["per_sample_timeout_s"], ecfg["grace_s"]
    max_n = ecfg["max_scored_samples"] or math.inf
    max_wall = ecfg["scored_max_wall_time_s"] or math.inf
    fail_col = K + 1
    pool.wait_ready()
    wait0 = pool.wait_ns
    cum, t0, end, n_correct = 0.0, _PC(), None, 0
    while end is None:
        acc = f"  acc={n_correct / st.n:.3f}" if st.n else ""
        status.set("scored", cum / budget, f"{cum:.1f}/{budget:g}s  n={st.n}{acc}")
        if st.n >= max_n:
            end = "max_samples"
            break
        if cum >= budget:
            end = "time_budget"
            break
        if (_PC() - t0) / 1e9 >= max_wall:
            end = "wall_clock"
            break
        item = pool.get()
        if item is None:
            end = "stream_exhausted"
            break
        i, series, meta, label, gen_ns = item
        res.generation_time_s += gen_ns / 1e9
        h.update(i, series, meta, label)
        remaining = budget - cum
        kind, val, p_ns, rt_ns = worker.predict(series, meta, min(per, remaining) + grace)
        if kind == "timeout" and remaining < per:
            worker.kill()  # it would have crossed the budget anyway: discard, not a hard timeout
            res.n_discarded += 1
            end = "time_budget"
            break
        if kind in ("timeout", "died"):
            worker.kill()
            charge = per if kind == "timeout" else min(rt_ns / 1e9, remaining)
            outcome = "hard_timeout" if kind == "timeout" else "exception"
            cum += charge
            st.record(i, label, fail_col, outcome, math.nan, charge)
            st.log_error("scored", i, outcome, "no answer within timeout + grace" if kind == "timeout" else "worker process died")
            reason = "hard_timeout" if kind == "timeout" else "worker_died"
            if ecfg["on_hard_timeout"] == "end_run":
                end = reason
                continue
            status.set("restart", None, reason)
            if not _restart(worker, res, "scored", reason, i, rt_ns):
                end = "restart_setup_failed"
            continue
        lat = p_ns / 1e9
        st.clock_check(p_ns, rt_ns)
        if cum + lat > budget:
            res.n_discarded += 1
            end = "time_budget"
            break
        cum += lat
        if lat > per:
            outcome, col = "soft_timeout", fail_col
        elif kind == "exception":
            outcome, col = "exception", fail_col
            st.log_error("scored", i, kind, val)
        elif kind == "invalid" or not (val == ABSTAIN or 0 <= val < K):
            outcome, col = "invalid", fail_col
            st.log_error("scored", i, "invalid", val if kind == "invalid" else f"int out of range: {val}")
        elif val == ABSTAIN:
            outcome, col = "abstain", K
        else:
            outcome, col = ("correct" if val == label else "incorrect"), val
        st.record(i, label, col, outcome, lat, lat)
        n_correct += outcome == "correct"
    res.end_reason, res.model_time_s = end, cum
    res.scored_wall_time_s = (_PC() - t0) / 1e9
    res.sample_wait_s = (pool.wait_ns - wait0) / 1e9


def class_geomean_score(s, eps=0.01, alpha=0.5, p=2):
    """Score = (prod_k T_k)^(1/K) with T_k = max(eps, n_k^alpha * (c_k - lambda*w_k)/n_k * (c_k/n_k)^p).

    Over the scored samples whose true class is k: n_k samples, c_k correct, w_k wrong
    (lambda = wrong_penalty; abstentions count in n_k but as neither correct nor wrong).
    alpha rewards speed (more samples answered), p rewards per-class precision.
    A class never drawn has c_k = w_k = 0, so its term is eps."""
    K = s.n_classes
    cm = np.asarray(s.confusion, dtype=float).reshape(K, -1)
    n = np.maximum(cm.sum(1), 1)  # avoid 0/0 for classes never drawn
    c = np.diag(cm[:, :K])
    w = cm.sum(1) - c - cm[:, K]
    t = n ** alpha * (c - s.wrong_penalty * w) / n * (c / n) ** p
    return float(np.exp(np.log(np.maximum(eps, t)).mean()))


def make_score_context(res, st, ecfg) -> SimpleNamespace:
    """Everything a score function can use. Attributes:

    * every RunResult field (n_correct, n_wrong, n_abstain, n_soft_timeout, n_hard_timeout,
      n_exception, n_invalid, n_discarded, n_scored, model_time_s, latency_s, confusion,
      per_class_accuracy, warmup_*, restarts, status, end_reason, ...),
    * config (the resolved EVAL_CONFIG), wrong_penalty (resolved), abstain_value,
      time_budget_s, per_sample_timeout_s, n_classes,
    * per-sample numpy arrays over scored samples: sample_index, y_true, y_pred (predicted
      column: class id, K = abstain, K+1 = failed), outcome (str), latency_s_per_sample
      (NaN when no answer) and charged_s.
    """
    K = res.n_classes
    d = asdict(res)
    d.update(config=ecfg,
             wrong_penalty=1.0 / (K - 1) if ecfg["wrong_penalty"] is None else float(ecfg["wrong_penalty"]),
             abstain_value=float(ecfg["abstain_value"]), time_budget_s=ecfg["time_budget_s"],
             per_sample_timeout_s=ecfg["per_sample_timeout_s"],
             sample_index=st.col("index"), y_true=st.col("y_true"), y_pred=st.col("y_pred"), outcome=st.outcomes(),
             latency_s_per_sample=st.col("latency"), charged_s=st.col("charged"))
    return SimpleNamespace(**d)


def _finalize(res, st, ecfg):
    K = res.n_classes
    cnt = dict(zip(OUTCOMES, np.bincount(st.col("outcome"), minlength=len(OUTCOMES)).tolist()))
    res.n_scored = st.n
    res.n_correct, res.n_incorrect, res.n_abstain = cnt["correct"], cnt["incorrect"], cnt["abstain"]
    res.n_soft_timeout, res.n_hard_timeout = cnt["soft_timeout"], cnt["hard_timeout"]
    res.n_exception, res.n_invalid = cnt["exception"], cnt["invalid"]
    res.n_guesses = res.n_correct + res.n_incorrect
    res.n_wrong = res.n_incorrect + res.n_soft_timeout + res.n_hard_timeout + res.n_exception + res.n_invalid
    res.accuracy_answered = res.n_correct / res.n_guesses if res.n_guesses else None
    res.accuracy_all = res.n_correct / res.n_scored if res.n_scored else None
    res.abstain_rate = res.n_abstain / res.n_scored if res.n_scored else None
    lat = st.col("latency")
    lat = lat[np.isfinite(lat)]
    if len(lat):
        res.latency_s = {"mean": float(lat.mean()), "median": float(np.median(lat)), "p95": float(np.percentile(lat, 95)),
                         "p99": float(np.percentile(lat, 99)), "max": float(lat.max())}
    res.throughput_per_s = res.n_scored / res.model_time_s if res.model_time_s > 0 else None
    cm = np.zeros((K, K + 2), dtype=np.int64)
    if res.n_scored:
        np.add.at(cm, (st.col("y_true"), st.col("y_pred")), 1)
    res.confusion = cm.tolist()
    res.confusion_columns = [str(k) for k in range(K)] + ["abstain", "failed"]
    rows = cm.sum(1)
    res.per_class_accuracy = [float(cm[k, k] / rows[k]) if rows[k] else None for k in range(K)]
    res.score = float(ecfg["score_fn"](make_score_context(res, st, ecfg)))


def _source_info(ecfg) -> dict:
    src = ecfg["source"]
    if src == "generator":
        if importlib.util.find_spec("generator") is None:
            raise EvalConfigError("the 'generator' source is organizer-only; evaluate on an exported file "
                                  "instead, e.g. --source file:train.npz")
        import generator
        dcfg = generator.resolve_config(ecfg["preset"])
        if generator.n_classes(dcfg) != N_CLASSES:
            raise EvalConfigError(f"dataset config has {generator.n_classes(dcfg)} classes but "
                                  f"competition_api.N_CLASSES = {N_CLASSES}")
        return {"source": src, "dcfg": dcfg, "hash": generator.config_hash(dcfg), "preset": ecfg["preset"]}
    path = Path(src[len("file:"):])
    if not path.exists():
        raise EvalConfigError(f"source file not found: {path} (relative to {Path.cwd()}); "
                              "download the training data or pass --source file:<path>")
    return {"source": src, "dcfg": None, "hash": None, "preset": None}


def run_once(project, model_path, r, ecfg, src=None, out_dir=None, status=None) -> RunResult:
    src = src or _source_info(ecfg)
    status = status or _LiveStatus(project, r, live=False)
    seeds = run_seeds(ecfg["master_seed"], r)
    res = RunResult(project=project, model_path=str(model_path), run=r, seeds=seeds, source=src["source"],
                    preset=src["preset"], dataset_config_hash=src["hash"], eval_config_hash=eval_config_hash(ecfg),
                    n_classes=N_CLASSES)
    st, h = _Run(res, ecfg), _StreamHash(ecfg["hash_checkpoints"])
    t0 = _PC()
    pools, worker = [], None
    log_path = None
    if out_dir:
        Path(out_dir).mkdir(parents=True, exist_ok=True)
        log_path = Path(out_dir) / f"run_{r}.worker.log"

    def pool(seed, stream):
        p = ProducerPool(src["source"], src["dcfg"], seed, stream, ecfg["n_producers"], ecfg["lookahead"],
                         ecfg["producer_cpu_affinity"], ecfg["producer_timeout_s"], ecfg["worker_env"])
        pools.append(p)
        return p
    try:
        warm = pool(seeds["warmup"], STREAM_WARMUP) if ecfg["warmup_enabled"] else None
        scored = pool(seeds["scored"], STREAM_SCORED)
        worker = _Worker(model_path, ecfg, seeds["participant"], log_path)
        status.set("setup", None, "Model()")
        ok, info, res.setup_time_s = worker.start()
        if not ok:
            res.status, res.failure_reason = "failed", info
        elif warm is None or _warmup(worker, warm, ecfg, res, st, status):
            if warm is not None:
                warm.close()
            _scored(worker, scored, ecfg, res, st, h, status)
    except ProducerError as e:
        res.status, res.failure_reason = "failed", f"producer_error: {str(e)[-2000:]}"
    finally:
        if worker is not None:
            worker.close()
        for p in pools:
            p.close()
    res.stream_hash, res.stream_samples, res.stream_hash_checkpoints = h.hexdigest(), h.n, h.points
    res.wall_time_s = (_PC() - t0) / 1e9
    _finalize(res, st, ecfg)
    if out_dir:
        _write_json(Path(out_dir) / f"run_{r}.json", asdict(res))
        if ecfg["save_per_sample"]:
            np.savez(Path(out_dir) / f"run_{r}.samples.npz", sample_index=st.col("index"),
                     y_true=st.col("y_true"), y_pred=st.col("y_pred"), outcome=np.asarray(OUTCOMES)[st.col("outcome")],
                     latency_s=st.col("latency"), charged_s=st.col("charged"))
    return res


