_CUSTOM_AGGREGATORS = {}


def register_aggregator(name, fn):
    """fn(list[RunResult]) -> float"""
    _CUSTOM_AGGREGATORS[name] = fn


def aggregators(ecfg) -> dict:
    trim, k = ecfg["trim_fraction"], ecfg["std_k"]

    def scores(rs):
        return np.array([r.score for r in rs], dtype=float)

    def trimmed_mean(rs):
        s = np.sort(scores(rs))
        c = int(trim * len(s))
        return float(s[c:len(s) - c].mean()) if len(s) > 2 * c else float(np.median(s))

    built = {
        "best": lambda rs: float(scores(rs).max()),
        "worst": lambda rs: float(scores(rs).min()),
        "mean": lambda rs: float(scores(rs).mean()),
        "median": lambda rs: float(np.median(scores(rs))),
        "trimmed_mean": trimmed_mean,
        "mean_minus_std": lambda rs: float(scores(rs).mean() - k * scores(rs).std()),
    }
    return {**built, **_CUSTOM_AGGREGATORS}


