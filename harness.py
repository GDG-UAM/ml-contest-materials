@contextlib.contextmanager
def _env(updates):
    old = {k: os.environ.get(k) for k in updates}
    os.environ.update({k: str(v) for k, v in updates.items()})
    try:
        yield
    finally:
        for k, v in old.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


def _set_affinity(cores):
    if not cores:
        return
    try:
        if hasattr(os, "sched_setaffinity"):
            os.sched_setaffinity(0, set(cores))
            return
        try:
            import psutil
            psutil.Process().cpu_affinity(list(cores))
        except ImportError:
            import ctypes
            k32 = ctypes.windll.kernel32
            k32.SetProcessAffinityMask(k32.GetCurrentProcess(), sum(1 << c for c in cores))
    except Exception as e:  # report, don't fail the run
        print(f"[harness] could not set CPU affinity {cores}: {e}", file=sys.stderr)


def _producer_main(source, dcfg, seed, stream_id, offset, step, q, affinity):
    _set_affinity(affinity)
    try:
        if source == "generator":
            import generator

            def get(i):
                return i, *generator.generate_sample(dcfg, seed, stream_id, i)
        else:
            ds = load_dataset(source[len("file:"):])
            # Read the rows in a seeded random order, different for every run and phase, like a stream.
            order = np.random.default_rng(seed).permutation(len(ds))

            def get(i):  # reports the file row j, so a logged error can be reproduced with ds[j]
                j = int(order[i]) if i < len(ds) else None
                return None if j is None else (j, np.array(ds.series[j]), ds.meta_at(j), int(ds.labels[j]))
        i = offset
        while True:
            t0 = time.perf_counter_ns()
            item = get(i)
            gen_ns = time.perf_counter_ns() - t0
            if item is None:
                q.put(("end", i))
                return
            q.put(("ok", item[0], item[1], item[2], int(item[3]), gen_ns))
            i += step
    except BaseException:
        q.put(("error", traceback.format_exc()))


class ProducerError(RuntimeError):
    pass


class ProducerPool:
    """n producer processes; producer j generates indices j, j+n, ... into its own bounded
    queue, so the parent reads samples in index order without reordering."""

    def __init__(self, source, dcfg, seed, stream_id, n, lookahead, affinity, timeout, env):
        ctx = mp.get_context("spawn")
        self.n, self.next, self.timeout, self.done = n, 0, timeout, False
        self.buffered, self.wait_ns = [], 0
        self.qs = [ctx.Queue(max(1, -(-lookahead // n))) for _ in range(n)]
        self.ps = [ctx.Process(target=_producer_main, daemon=True,
                               args=(source, dcfg, seed, stream_id, j, n, self.qs[j], affinity)) for j in range(n)]
        with _env(env):
            for p in self.ps:
                p.start()

    def wait_ready(self):
        """Block until the next sample exists, so producer start-up stays out of phase timers."""
        if not self.buffered:
            self.buffered.append(self._fetch())

    def get(self):
        """Next sample (i, series, meta, label, gen_ns), or None at the end of a finite stream."""
        return self.buffered.pop() if self.buffered else self._fetch()

    def _fetch(self):
        if self.done:
            return None
        t0 = _PC()
        try:
            item = self.qs[self.next % self.n].get(timeout=self.timeout)
        except queue.Empty:
            raise ProducerError(f"no sample {self.next} within {self.timeout}s") from None
        finally:
            self.wait_ns += _PC() - t0
        if item[0] == "error":
            raise ProducerError(item[1])
        if item[0] == "end":
            self.done = True
            return None
        self.next += 1
        return item[1:]

    def close(self):
        for p in self.ps:
            if p.is_alive():
                p.kill()
        for p in self.ps:
            p.join(5)
        for q in self.qs:
            q.cancel_join_thread()
            q.close()


def _seed_torch(seed, mode, state):
    if mode == "never" or state.get("done"):
        return
    if mode == "if_installed" and "torch" not in sys.modules and importlib.util.find_spec("torch"):
        import torch  # noqa: F401
    t = sys.modules.get("torch")
    if t is not None:
        t.manual_seed(seed)
        state["done"] = True


def _worker_main(conn, model_path, opts):
    if opts["log_path"]:
        f = open(opts["log_path"], "a", buffering=1, encoding="utf-8", errors="replace")
        with contextlib.suppress(Exception):
            sys.stdout.flush(), sys.stderr.flush()
            os.dup2(f.fileno(), 1)
            os.dup2(f.fileno(), 2)
        sys.stdout = sys.stderr = f
    _set_affinity(opts["affinity"])
    seed, torch_state = opts["seed"], {}
    if seed is not None:
        random.seed(seed)
        np.random.seed(seed)
        _seed_torch(seed, opts["seed_torch"], torch_state)
    model_path = os.path.abspath(model_path)
    sys.path.insert(0, os.path.dirname(model_path))
    if opts["chdir"]:
        os.chdir(os.path.dirname(model_path))
    try:
        spec = importlib.util.spec_from_file_location("participant_model", model_path)
        mod = importlib.util.module_from_spec(spec)
        sys.modules["participant_model"] = mod
        spec.loader.exec_module(mod)
        if seed is not None:
            _seed_torch(seed, opts["seed_torch"], torch_state)
        model = mod.Model()
        if seed is not None:
            _seed_torch(seed, opts["seed_torch"], torch_state)
    except BaseException:
        conn.send(("setup_error", traceback.format_exc(limit=20)[-4000:], None))
        return
    conn.send(("ready", None, None))
    while True:
        try:
            msg = conn.recv()
        except (EOFError, OSError):
            return
        if msg[0] != "predict":
            return
        x = Sample(np.frombuffer(msg[1], dtype=np.float32).reshape(msg[2]), msg[3])  # fully built before timing
        t0 = _PC()
        try:
            y = model.predict(x)
        except BaseException as e:
            t1 = _PC()
            out = ("exception", f"{type(e).__name__}: {str(e)[:300]}\n{traceback.format_exc(limit=5)[-1500:]}")
        else:
            t1 = _PC()
            if isinstance(y, (int, np.integer)) and not isinstance(y, (bool, np.bool_)):
                out = ("ok", int(y))
            else:
                try:
                    out = ("invalid", f"{type(y).__name__}: {repr(y)[:200]}")
                except BaseException:
                    out = ("invalid", type(y).__name__)
        try:
            conn.send((out[0], out[1], t1 - t0))
        except (EOFError, OSError):
            return


class _Worker:
    """Parent-side handle of the participant worker process."""

    def __init__(self, model_path, ecfg, seed, log_path):
        self.model_path, self.ecfg, self.seed, self.log_path = str(model_path), ecfg, seed, log_path
        self.proc = self.conn = None

    def start(self):
        """Spawn and run setup. Returns (ok, info, setup_seconds)."""
        ctx = mp.get_context("spawn")
        self.conn, child = ctx.Pipe(duplex=True)
        opts = {"seed": self.seed if self.ecfg["seed_participant_rngs"] else None,
                "seed_torch": self.ecfg["seed_torch"], "affinity": self.ecfg["worker_cpu_affinity"],
                "chdir": self.ecfg["worker_chdir"], "log_path": str(self.log_path) if self.log_path else None}
        env = dict(self.ecfg["worker_env"])
        if self.ecfg["seed_participant_rngs"]:
            env["PYTHONHASHSEED"] = str(self.seed)
        self.proc = ctx.Process(target=_worker_main, args=(child, self.model_path, opts), name="participant-worker")
        t0 = _PC()
        with _env(env):
            self.proc.start()
        child.close()
        timeout = self.ecfg["setup_timeout_s"]
        try:
            if not self.conn.poll(timeout):
                self.kill()
                return False, f"setup_timeout ({timeout}s)", (_PC() - t0) / 1e9
            kind, info, _ = self.conn.recv()
        except (EOFError, OSError):
            self.kill()
            return False, "setup_error: worker died during setup", (_PC() - t0) / 1e9
        dt = (_PC() - t0) / 1e9
        if kind != "ready":
            self.kill()
            return False, f"setup_error: {info}", dt
        return True, None, dt

    def predict(self, series, meta, limit_s):
        """Returns (kind, value, predict_ns, roundtrip_ns); kind in ok|invalid|exception|timeout|died."""
        t0 = _PC()
        try:
            self.conn.send(("predict", series.tobytes(), series.shape, meta))
            if not self.conn.poll(limit_s):
                return "timeout", None, None, _PC() - t0
            kind, val, p_ns = self.conn.recv()
        except (EOFError, OSError):
            return "died", None, None, _PC() - t0
        return kind, val, p_ns, _PC() - t0

    def kill(self):
        if self.proc is not None and self.proc.is_alive():
            self.proc.kill()
        if self.proc is not None:
            self.proc.join(5)
        if self.conn is not None:
            self.conn.close()
        self.proc = self.conn = None

    def close(self):
        if self.conn is not None:
            with contextlib.suppress(Exception):
                self.conn.send(("stop",))
        if self.proc is not None:
            self.proc.join(2)
        self.kill()


