def _write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, default=lambda o: o.item() if isinstance(o, np.generic) else str(o)))


def evaluate_project(model_path, ecfg, project=None, out_dir=None, src=None, verbose=False):
    """Run ecfg['n_runs'] runs. Returns (summary dict, list[RunResult])."""
    project = project or Path(model_path).stem
    src = src or _source_info(ecfg)
    pdir = Path(out_dir) / project if out_dir else None
    runs = []
    for r in range(ecfg["n_runs"]):
        with _LiveStatus(project, r, live=verbose) as status:
            res = run_once(project, model_path, r, ecfg, src, pdir, status)
        runs.append(res)
        if verbose:
            print(_run_line(res), file=sys.stderr)
            if res.status != "ok" and pdir:
                print(_paint(f"    details: {pdir / f'run_{r}.json'}, run_{r}.worker.log", "dim"), file=sys.stderr)
    aggs = {name: float(f(runs)) for name, f in aggregators(ecfg).items()}
    summary = {
        "project": project, "model_path": str(model_path), "n_runs": len(runs),
        "ranking_metric": ecfg["aggregation"], "ranking_score": aggs[ecfg["aggregation"]], "aggregates": aggs,
        "failed_runs": sum(r.status != "ok" for r in runs),
        "dataset_config_hash": src["hash"], "eval_config_hash": eval_config_hash(ecfg),
        "mean_accuracy_all": _mean([r.accuracy_all for r in runs]),
        "mean_n_scored": float(np.mean([r.n_scored for r in runs])),
        "mean_latency_s": _mean([r.latency_s.get("mean") for r in runs]),
        "runs": [{k: getattr(r, k) for k in ("run", "status", "failure_reason", "score", "n_scored", "accuracy_all",
                                             "accuracy_answered", "end_reason", "model_time_s", "stream_hash",
                                             "stream_samples", "warmup_samples", "warmup_end_reason")} for r in runs],
    }
    if pdir:
        _write_json(pdir / "aggregate.json", summary)
    return summary, runs


def _mean(xs):
    xs = [x for x in xs if x is not None]
    return float(np.mean(xs)) if xs else None


def _project_names(paths):
    stems = [Path(p).stem for p in paths]
    names = [s if stems.count(s) == 1 else f"{Path(p).parent.name}_{s}" for p, s in zip(paths, stems)]
    return [n if names.count(n) == 1 else f"{n}_{j}" for j, n in enumerate(names)]


def leaderboard(summaries, ecfg, out_dir=None, color=False):
    rows = sorted(summaries, key=lambda s: -s["ranking_score"])
    agg_names = list(aggregators(ecfg))
    header = ["rank", "project", ecfg["aggregation"], *[a for a in agg_names if a != ecfg["aggregation"]],
              "failed_runs", "mean_accuracy_all", "mean_n_scored", "mean_latency_s"]
    table = []
    for j, s in enumerate(rows, 1):
        table.append([j, s["project"], s["ranking_score"], *[s["aggregates"][a] for a in agg_names if a != ecfg["aggregation"]],
                      s["failed_runs"], s["mean_accuracy_all"], s["mean_n_scored"], s["mean_latency_s"]])
    if out_dir:
        Path(out_dir).mkdir(parents=True, exist_ok=True)
        with open(Path(out_dir) / "leaderboard.csv", "w", newline="") as f:
            csv.writer(f).writerows([header, *table])

    def fmt(v):
        return "-" if v is None else f"{v:.4g}" if isinstance(v, float) else str(v)

    def paint(text, *styles):
        return _paint(text, *styles, stream=sys.stdout) if color else text
    cells = [header] + [[fmt(v) for v in row] for row in table]
    widths = [max(len(r[c]) for r in cells) for c in range(len(header))]
    padded = [[v.rjust(w) if c != 1 else v.ljust(w) for c, (v, w) in enumerate(zip(r, widths))] for r in cells]
    head = "  ".join(padded[0])
    lines = [paint(head, "bold"), paint("-" * len(head), "dim")]
    for row in padded[1:]:  # padding first, then color, so the escape codes don't skew the widths
        row[1], row[2] = paint(row[1], "cyan"), paint(row[2], "bold")  # project, ranking score
        lines.append("  ".join(row))
    return "\n".join(lines)


def evaluate(model_paths, ecfg, out_dir=None, verbose=True):
    src = _source_info(ecfg)
    summaries = []
    for path, name in zip(model_paths, _project_names(model_paths)):
        if verbose:
            print(f"{_paint('evaluating', 'bold')} {_paint(name, 'bold', 'cyan')} {_paint(f'({path})', 'dim')}",
                  file=sys.stderr)
        summaries.append(evaluate_project(path, ecfg, name, out_dir, src, verbose)[0])
    table = leaderboard(summaries, ecfg, out_dir, color=verbose and _color(sys.stdout))
    if verbose:
        print(table)
    return summaries


def _parse_set(items):
    out = {}
    for item in items or []:
        k, _, v = item.partition("=")
        try:
            out[k] = json.loads(v)
        except json.JSONDecodeError:
            out[k] = v
    return out


def _warn(title, *lines):
    """Print 'WARNING: title' plus indented lines to stderr: bold yellow title, URLs in cyan."""
    body = [_paint(ln, "cyan") if ln.startswith("http") else ln for ln in lines]
    print(_paint(f"WARNING: {title}", "bold", "yellow"), *(f"  {ln}" for ln in body), sep="\n", file=sys.stderr)


def _harness_digest() -> str:
    """sha256 of this file without the HARNESS_SHA256 line, with LF line endings (git may check out CRLF)."""
    lines = Path(__file__).read_bytes().replace(b"\r\n", b"\n").splitlines(keepends=True)
    return hashlib.sha256(b"".join(ln for ln in lines if not ln.startswith(b"HARNESS_SHA256 = "))).hexdigest()


# string literals starting like an absolute path: "C:\...", "C:/...", "/home/...", "~/..."
_ABS_PATH = re.compile(r"""["'](?:[A-Za-z]:[\\/]|/\w|~[\\/])""")


def _warn_absolute_paths(model_path):
    # ponytail: line regex over the model file only; helper modules it imports are not scanned
    try:
        lines = Path(model_path).read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return  # a missing file is reported by the run itself
    hits = [f"line {j}: {ln.strip()[:100]}" for j, ln in enumerate(lines, 1)
            if _ABS_PATH.search(ln) and not ln.lstrip().startswith("#")]
    if hits:
        _warn(f"{model_path} seems to use absolute paths, which will not exist on the evaluation machine:",
              *hits, 'Load files relative to your model file instead, e.g. Path(__file__).parent / "weights.pt".')


def main(argv=None):
    if _harness_digest() != HARNESS_SHA256:
        _warn("harness.py differs from the official version (checksum mismatch).",
              "This file will be ignored in the real evaluation, and any change here will not persist.",
              "It is recommended to use the official harness to ensure compatibility:", OFFICIAL_HARNESS_URL)
    ap = argparse.ArgumentParser(description="Evaluate participant models.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("evaluate")
    e.add_argument("--model", action="append", required=True, help="participant file (repeatable)")
    e.add_argument("--runs", type=int)
    e.add_argument("--preset")
    e.add_argument("--aggregation")
    e.add_argument("--source", help="generator (default) or file:<path>")
    e.add_argument("--out", default="results")
    e.add_argument("--set", action="append", metavar="KEY=VALUE", help="override any EVAL_CONFIG key (JSON value)")
    a = ap.parse_args(argv)
    overrides = _parse_set(a.set)
    for key, val in (("n_runs", a.runs), ("preset", a.preset), ("aggregation", a.aggregation), ("source", a.source)):
        if val is not None:
            overrides[key] = val
    for m in a.model:
        _warn_absolute_paths(m)
    try:
        evaluate(a.model, resolve_eval_config(overrides), a.out)
    except EvalConfigError as e:
        sys.exit(_paint(f"error: {e}", "bold", "red"))


if __name__ == "__main__":
    main()
