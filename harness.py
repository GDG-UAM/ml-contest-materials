"""Sequential, time-limited evaluation harness (the same file is used for the official evaluation).

Per run: fresh worker process (participant code) + producer processes (sample generation/reading).
Phases: setup (untimed, with timeout) -> warmup (unscored) -> scored (strictly sequential,
until the cumulative predict-time budget, the sample cap or the wall-clock safety limit).

Participants evaluate locally on the training file (by default data/train_100k.npz, relative to
the current directory; the generator source is organizer-only):

    python harness.py evaluate --model path/to/model.py [--set time_budget_s=30]

Full CLI:

    python harness.py evaluate --model a.py [--model b.py ...] [--runs N] [--preset NAME]
                               [--aggregation NAME] [--source generator|file:<path.npz>]
                               [--set key=json_value ...] [--out results/]

Paths: your model runs with its own directory as the working directory (also on sys.path),
locally and in the official evaluation. Load weights relative to your model file, e.g.
``Path(__file__).parent / "weights.pt"``. Absolute paths (C:/Users/..., /home/...) will not exist
on the evaluation machine; the CLI warns when it spots one in your model file.

Do not edit this file to change the rules: the official evaluation uses its own copy, and the CLI
warns when this file differs from it. Official version: see OFFICIAL_HARNESS_URL below.
"""
